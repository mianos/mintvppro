#!/usr/bin/env python3
"""Regenerates the nixie face art in main/ from nixie.html.

Renders the page in headless Chrome (macOS path; set CHROME to override) and writes
nixie_bg.bin, nixie_glow.bin, nixie_text.bin and NixieArt.h. Run after changing
the drawing; the outputs are checked in, so normal builds don't need this.
"""
import base64
import html
import json
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAIN = HERE.parent.parent / "main"
CHROME = os.environ.get("CHROME", "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome")


def render() -> dict:
    dom = subprocess.run(
        [CHROME, "--headless=new", "--virtual-time-budget=5000", "--dump-dom",
         (HERE / "nixie.html").as_uri() + "#export"],
        check=True, capture_output=True, text=True).stdout
    m = re.search(r'<pre id="out">(.*?)</pre>', dom, re.S)
    if not m:
        sys.exit("nixie.html produced no export (font missing?)")
    return json.loads(html.unescape(m.group(1)))


def main() -> None:
    d = render()
    bg = base64.b64decode(d["bg"])
    assert len(bg) == 240 * 240 * 2
    cell = d["cell_w"] * d["cell_h"]
    digits = [base64.b64decode(x) for x in d["digits"]]
    assert len(digits) == 10 and all(len(x) == cell for x in digits)
    co = d["colon"]
    colon = base64.b64decode(d["colon_px"])
    assert len(colon) == co["w"] * co["h"]
    lamp = base64.b64decode(d["lamp_px"])
    assert len(lamp) == d["lamp"] ** 2

    glyphs, alpha, offset = [], [], 0
    for g in d["glyphs"]:
        a = base64.b64decode(g["alpha"])
        assert len(a) == g["w"] * d["text_h"]
        glyphs.append(f"    {{{offset}, {g['w']}, {g['adv']}, {g['left']}}},")
        alpha.append(a)
        offset += len(a)

    (MAIN / "nixie_bg.bin").write_bytes(bg)
    (MAIN / "nixie_glow.bin").write_bytes(b"".join(digits) + colon + lamp)
    (MAIN / "nixie_text.bin").write_bytes(b"".join(alpha))

    ramp = "\n".join("    " + " ".join(f"{{{r}, {g}, {b}}}," for r, g, b in d["ramp"][i:i + 8])
                     for i in range(0, 256, 8))
    glyph_table = "\n".join(glyphs)
    cx = ", ".join(str(x) for x in d["digit_cx"])
    (MAIN / "NixieArt.h").write_text(f"""#pragma once
// Generated by tools/nixie/gen.py from tools/nixie/nixie.html; do not edit.
//
// nixie_bg.bin   240x240 big-endian RGB565: the glass with unlit cathodes, standing
//                on a wooden base with a brass plate for the text.
// nixie_glow.bin glow intensity (0-255) for lit digits 0-9, kCellW x kCellH each,
//                then the lit colon, then the Wi-Fi lamp (kLamp square, at 0,0);
//                kRamp turns intensity into added colour.
// nixie_text.bin 8-bit coverage maps, kTextH rows each, for the glyphs in kGlyphs.
#include <cstdint>

namespace nixie {{
inline constexpr int kBgBytes = 240 * 240 * 2;

inline constexpr int kDigitCx[4] = {{{cx}}};
inline constexpr int kCellW = {d["cell_w"]};
inline constexpr int kCellH = {d["cell_h"]};
inline constexpr int kCellY = {d["cell_y"]};
inline constexpr int kColonX = {co["x"]};
inline constexpr int kColonY = {co["y"]};
inline constexpr int kColonW = {co["w"]};
inline constexpr int kColonH = {co["h"]};
inline constexpr int kColonOffset = 10 * kCellW * kCellH;
inline constexpr int kLamp = {d["lamp"]};
inline constexpr int kLampOffset = kColonOffset + kColonW * kColonH;
inline constexpr int kGlowBytes = kLampOffset + kLamp * kLamp;

inline constexpr uint8_t kRamp[256][3] = {{
{ramp}
}};

struct Glyph {{
    uint32_t offset;  // into nixie_text.bin
    uint8_t w;        // bitmap columns
    uint8_t advance;
    int8_t left;      // bitmap x relative to the pen
}};
inline constexpr int kTextY[2] = {{{d["text_y"][0]}, {d["text_y"][1]}}};
inline constexpr int kTextH = {d["text_h"]};
inline constexpr uint8_t kTextRgb[3] = {{{d["text_rgb"][0]}, {d["text_rgb"][1]}, {d["text_rgb"][2]}}};
inline constexpr char kFirstGlyph = 0x20;
inline constexpr char kDegree = 0x7F;  // stands in for the degree sign
inline constexpr Glyph kGlyphs[] = {{
{glyph_table}
}};
inline constexpr int kTextBytes = {offset};
}}  // namespace nixie
""")
    print(f"bg {len(bg)} bytes, glow {len(digits) * cell + len(colon) + len(lamp)} bytes "
          f"(cell {d['cell_w']}x{d['cell_h']}), {len(glyphs)} glyphs {offset} bytes")


if __name__ == "__main__":
    main()
