#!/usr/bin/env python3
"""Regenerates the VFD face art in main/ from vfd.html.

Renders the page in headless Chrome (macOS path; set CHROME to override) and writes
vfd_bg.bin, vfd_glow.bin and VfdArt.h. Run after changing the drawing; the outputs
are checked in, so normal builds don't need this.
"""
import base64
import html
import json
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAIN = HERE.parent.parent / "main"
CHROME = os.environ.get("CHROME", "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome")


def render() -> dict:
    dom = subprocess.run(
        [CHROME, "--headless=new", "--virtual-time-budget=5000", "--dump-dom",
         (HERE / "vfd.html").as_uri() + "#export"],
        check=True, capture_output=True, text=True).stdout
    m = re.search(r'<pre id="out">(.*?)</pre>', dom, re.S)
    if not m:
        sys.exit("vfd.html produced no export (font missing?)")
    return json.loads(html.unescape(m.group(1)))


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    d = render()
    bg = base64.b64decode(d["bg"])
    assert len(bg) == 240 * 240 * 2

    glow = bytearray()
    decls = []

    def font(name: str, f: dict) -> None:
        offset = len(glow)
        for px in f["px"]:
            b = base64.b64decode(px)
            assert len(b) == f["w"] * f["h"]
            glow.extend(b)
        xs = ", ".join(str(x) for x in f["xs"])
        decls.append(f"inline constexpr Font k{name} = {{{f['w']}, {f['h']}, {f['y']}, {offset}, {c_str(f['chars'])}}};\n"
                     f"inline constexpr int k{name}X[{len(f['xs'])}] = {{{xs}}};")

    def cell(name: str, a: dict) -> None:
        b = base64.b64decode(a["px"])
        assert len(b) == a["w"] * a["h"]
        decls.append(f"inline constexpr Cell k{name} = {{{a['x']}, {a['y']}, {a['w']}, {a['h']}, {len(glow)}}};")
        glow.extend(b)

    font("Big", d["big"])
    font("Half", d["half"])
    font("Small", d["small"])
    font("Alnum", d["alnum"])
    font("Tiny", d["tiny"])
    for k, a in d["ann"].items():
        cell(k[0].upper() + k[1:], a)
    dp = d["dp"]
    for i, x in enumerate(dp["xs"]):
        decls.append(f"inline constexpr Cell kDp{i} = {{{x}, {dp['y']}, {dp['w']}, {dp['h']}, {len(glow)}}};")
    glow.extend(base64.b64decode(dp["px"]))

    (MAIN / "vfd_bg.bin").write_bytes(bg)
    (MAIN / "vfd_glow.bin").write_bytes(bytes(glow))

    def table(rows):
        return "\n".join("    " + " ".join(f"{{{r}, {g}, {b}}}," for r, g, b in rows[i:i + 8])
                         for i in range(0, 256, 8))
    ramp, filter_ramp = table(d["ramp"]), table(d["filter_ramp"])
    body = "\n".join(decls)
    (MAIN / "VfdArt.h").write_text(f"""#pragma once
// Generated by tools/vfd/gen.py from tools/vfd/vfd.html; do not edit.
//
// vfd_bg.bin   240x240 big-endian RGB565: the display with every segment unlit.
// vfd_glow.bin glow intensity (0-255) maps; kRamp turns intensity into added colour.
#include <cstdint>

namespace vfd {{
inline constexpr int kBgBytes = 240 * 240 * 2;

// A segment font: one w x h cell per char in chars, from offset in vfd_glow.bin.
// Each cell's top-left goes at (x from the font's X table, y).
struct Font {{
    int w, h, y;
    uint32_t offset;
    const char* chars;
}};

// One lit element, drawn at (x, y).
struct Cell {{
    int x, y, w, h;
    uint32_t offset;
}};

{body}
inline constexpr int kGlowBytes = {len(glow)};

inline constexpr uint8_t kRamp[256][3] = {{
{ramp}
}};
// For everything behind the amber filter: the sun, moon and sunset time, and the
// temperature and date rows (digits, decimal points, trend arrows).
inline constexpr uint8_t kFilterRamp[256][3] = {{
{filter_ramp}
}};
}}  // namespace vfd
""")
    print(f"bg {len(bg)} bytes, glow {len(glow)} bytes")


if __name__ == "__main__":
    main()
